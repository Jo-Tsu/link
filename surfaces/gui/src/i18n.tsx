const STORAGE_KEY = "link:language:v1";

function interpolate(template: string, params?: TranslationParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (
    params[key] === undefined ? match : String(params[key])
  ));
}

function initialLanguage(): AppLanguage {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "zh-CN" || stored === "en") return stored;
  } catch {
    // Fall through to the system locale.
  }
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

interface LanguageContextValue {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (key: TranslationKey) => string;
  tr: (english: string, params?: TranslationParams) => string;
  locale: string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>(initialLanguage);
  const setLanguage = (next: AppLanguage) => {
    setLanguageState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // The current session still changes even when localStorage is unavailable.
    }
  };
  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dataset.language = language;
    void setAppLanguage(language);
  }, [language]);
  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      setLanguage,
      t: (key) => applyProductBrand(language === "zh-CN" ? zh[key] : en[key]),
      tr: (english, params) => applyProductBrand(interpolate(
        language === "zh-CN" ? (zhCopy[english] || english) : english,
        params,
      )),
      locale: language === "zh-CN" ? "zh-CN" : "en-US",
    }),
    [language],
  );
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

const fallbackLanguageContext: LanguageContextValue = {
  language: "en",
  setLanguage: () => {},
  t: (key) => applyProductBrand(en[key]),
  tr: (english, params) => applyProductBrand(interpolate(english, params)),
  locale: "en-US",
};

export function useI18n(): LanguageContextValue {
  return useContext(LanguageContext) ?? fallbackLanguageContext;
}
